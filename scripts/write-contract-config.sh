COINTAG_MANAGER=$(python3 -c "import json,sys; d=json.load(open('$JSON')); print(d['coinTagManager'])")
PAYMENT_MANAGER=$(python3 -c "import json,sys; d=json.load(open('$JSON')); print(d['paymentManager'])")

OUT="src/contractConfig.ts"

