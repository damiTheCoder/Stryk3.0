#!/usr/bin/env bash
# scripts/write-contract-config.sh
# Reads contracts/out/deployed-addresses.json and writes src/contractConfig.ts.
# Run this after: forge script contracts/script/Deploy.s.sol:Deploy --broadcast ...
set -euo pipefail

JSON="contracts/out/deployed-addresses.json"

if [ ! -f "$JSON" ]; then
  echo "Error: $JSON not found. Run the Deploy script first." >&2
  exit 1
fi

# Parse addresses from JSON (using python3, available on macOS by default)
